<?php

declare(strict_types=1);

namespace Bidirekt\PhpSdk\Tests;

use PHPUnit\Framework\TestCase;

final class PackageTest extends TestCase
{
    private const REPOSITORY = __DIR__ . '/..';

    private const PET_SOURCE = <<<'PHP'
        <?php

        namespace App;

        use Bidirekt\PhpSdk\BidirektField;
        use Bidirekt\PhpSdk\BidirektSchema;

        #[BidirektSchema]
        final class Pet
        {
            #[BidirektField]
            public int $id;

            #[BidirektField(description: 'The name the owner calls the pet')]
            public string $name;
        }

        PHP;

    private const PET_CONTRACT = <<<'YAML'
        # Generated by bidirekt/php-sdk. Do not edit.
        schemas:
          Pet:
            type: object
            properties:
              id:
                type: integer
              name:
                type: string
                description: The name the owner calls the pet

        YAML;

    private string $workspace;

    protected function setUp(): void
    {
        $this->workspace = sys_get_temp_dir() . '/php-sdk-package-' . bin2hex(random_bytes(6));
        mkdir($this->workspace);
    }

    protected function tearDown(): void
    {
        self::removeDirectory($this->workspace);
    }

    public function testInstallsFromAPathRepositoryWithoutTheExportIgnoredFilesAndGenerates(): void
    {
        $composer = self::composerBinary();
        if ($composer === null) {
            self::markTestSkipped('composer is not installed: run the tests with composer test');
        }
        $manifest = [
            'repositories' => [
                ['type' => 'path', 'url' => (string) realpath(self::REPOSITORY), 'options' => ['symlink' => false]],
            ],
            'require-dev' => ['bidirekt/php-sdk' => '*@dev'],
            'autoload' => ['psr-4' => ['App\\' => 'src/'], 'files' => ['bootstrap.php']],
        ];
        file_put_contents($this->workspace . '/composer.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
        mkdir($this->workspace . '/src');
        file_put_contents($this->workspace . '/src/Pet.php', self::PET_SOURCE);
        file_put_contents($this->workspace . '/bootstrap.php', "<?php\nfile_put_contents(__DIR__ . '/bootstrapped.txt', 'ran');\n");

        [$installCode, $installOutput] = $this->runInWorkspace([PHP_BINARY, $composer, 'install', '--no-interaction', '--no-progress']);
        self::assertSame(0, $installCode, $installOutput);

        $installed = $this->workspace . '/vendor/bidirekt/php-sdk';
        self::assertFileExists($installed . '/bin/php-sdk');
        self::assertFileExists($installed . '/src/BidirektSchema.php');
        self::assertDirectoryDoesNotExist($installed . '/tests');
        self::assertDirectoryDoesNotExist($installed . '/vendor');

        [$generateCode, $generateOutput] = $this->runInWorkspace([PHP_BINARY, 'vendor/bin/php-sdk', 'generate']);
        self::assertSame('', $generateOutput, 'output');
        self::assertSame(0, $generateCode, 'exit code');
        self::assertSame(self::PET_CONTRACT, file_get_contents($this->workspace . '/contracts/generated.yaml'));
        self::assertFileDoesNotExist($this->workspace . '/bootstrapped.txt', 'the project autoload files ran');
    }

    private static function composerBinary(): ?string
    {
        $fromComposerScript = getenv('COMPOSER_BINARY');
        if (is_string($fromComposerScript) && is_file($fromComposerScript)) {
            return $fromComposerScript;
        }
        foreach (explode(PATH_SEPARATOR, (string) getenv('PATH')) as $directory) {
            if (is_file($directory . '/composer')) {
                return $directory . '/composer';
            }
        }

        return null;
    }

    /**
     * @param list<string> $command
     *
     * @return array{int, string} the exit code and stdout and stderr merged
     */
    private function runInWorkspace(array $command): array
    {
        $output = tmpfile();
        self::assertIsResource($output);
        $process = proc_open($command, [1 => $output, 2 => $output], $pipes, $this->workspace);
        self::assertIsResource($process);
        $exitCode = proc_close($process);
        rewind($output);

        return [$exitCode, (string) stream_get_contents($output)];
    }

    private static function removeDirectory(string $directory): void
    {
        foreach (array_diff((array) scandir($directory), ['.', '..']) as $entry) {
            $path = $directory . '/' . $entry;
            if (is_dir($path) && !is_link($path)) {
                self::removeDirectory($path);

                continue;
            }
            unlink($path);
        }
        rmdir($directory);
    }
}
