    public function testWritesEveryNodeTypeAndFlagInTheFixedOrder(): void
    {
        self::assertSame(self::FULL_YAML, ContractToYaml::contractToYaml(self::fullContract()));
    }

    public function testWritesTheSameTextForTheSameModel(): void
    {
        self::assertSame(
            ContractToYaml::contractToYaml(self::fullContract()),
            ContractToYaml::contractToYaml(self::fullContract()),
        );
    }

    public function testWritesTheSameTextWhenResourcesAndSchemasArriveInAnotherOrder(): void
    {
        $contract = self::fullContract();
        $reversed = new Contract(
            array_reverse(array_map(
                static fn(ProvidedResource $resource): ProvidedResource => new ProvidedResource(
                    $resource->method,
                    $resource->path,
                    $resource->request,
                    array_reverse($resource->responses),
                    $resource->location,
                ),
                $contract->provides,
            )),
            array_reverse($contract->consumes),
            array_reverse($contract->schemas),
        );

        self::assertSame(self::FULL_YAML, ContractToYaml::contractToYaml($reversed));
    }

    public function testOmitsEmptySectionsAndTheRequestKeyWhenNoneWasDeclared(): void
    {
        $at = new SourceLocation('src/Pets.php', 1);
        $contract = new Contract([], [
            new ConsumedResource('payments_api', 'GET', '/charges/*', null, [new Response(200, new Body(null, $at))], $at),
        ]);

        self::assertSame(
            self::HEADER . <<<'YAML'
                consumes:
                  payments_api:
                    rest:
                      /charges/*:
                        get:
                          responses:
                            200: ~

                YAML,
            ContractToYaml::contractToYaml($contract),
        );
    }

    public function testWritesAnEmptyContractAsAnEmptyMap(): void
    {
        self::assertSame(self::HEADER . "{}\n", ContractToYaml::contractToYaml(new Contract()));
    }

    public function testWritesEmptyCollectionsInFlowStyle(): void
    {
        $at = new SourceLocation('src/Pets.php', 1);
        $contract = new Contract([new ProvidedResource('GET', '/pets', null, [], $at)], [], [
            new NamedSchema('Empty', new ObjectNode([]), $at),
            new NamedSchema('Nothing', new EnumNode([]), $at),
            new NamedSchema('Neither', new UnionNode([]), $at),
        ]);

        self::assertSame(
            self::HEADER . <<<'YAML'
                provides:
                  rest:
                    /pets:
                      get:
                        responses: {}
                schemas:
                  Empty:
                    type: object
                    properties: {}
                  Neither:
                    type: union
                    members: {}
                  Nothing:
                    type: enum
                    members: []

                YAML,
            ContractToYaml::contractToYaml($contract),
        );
    }

