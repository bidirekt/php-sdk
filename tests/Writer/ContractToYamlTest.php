    public function testWritesAKeyLongerThan1024CharactersAsAnExplicitKey(): void
    {
        $at = new SourceLocation('src/Pets.php', 1);
        $name = str_repeat('x', 1025);
        $contract = new Contract([], [], [new NamedSchema($name, new RefNode('Pet'), $at)]);

        self::assertSame(
            self::HEADER . "schemas:\n  ? {$name}\n  : ref: Pet\n",
            ContractToYaml::contractToYaml($contract),
        );
    }

    public function testQuotesFreeTextOnlyWhereYamlWouldReadItAsSomethingElse(): void
    {
        $at = new SourceLocation('src/Pet.php', 1);
        $properties = [];
        foreach (self::FREE_TEXT_DESCRIPTIONS as [$name, $description]) {
            $node = new PrimitiveNode('string');
            $node->description = $description;
            $properties[] = new Property($name, $node, $at);
        }
        $contract = new Contract([], [], [new NamedSchema('Pet', new ObjectNode($properties), $at)]);

        self::assertSame(self::HEADER . self::FREE_TEXT_YAML, ContractToYaml::contractToYaml($contract));
    }

    private static function fullContract(): Contract
    {
        $at = new SourceLocation('src/Pets.php', 1);

        return new Contract(
            [
                new ProvidedResource(
                    'POST',
                    '/pets',
                    new Body('NewPet', $at),
                    [new Response(400, new Body(null, $at)), new Response(201, new Body('Pet', $at))],
                    $at,
                ),
                new ProvidedResource(
                    'GET',
                    '/pets/*',
                    null,
                    [new Response(404, new Body(null, $at)), new Response(200, new Body('Pet', $at))],
                    $at,
                ),
                new ProvidedResource('GET', '/pets', null, [new Response(200, new Body('PetList', $at))], $at),
                new ProvidedResource('DELETE', '/pets/*', new Body(null, $at), [new Response(204, new Body(null, $at))], $at),
            ],
            [
                new ConsumedResource(
                    'payments_api',
                    'POST',
                    '/charges',
                    new Body('NewCharge', $at),
                    [new Response(201, new Body('Charge', $at))],
                    $at,
                ),
                new ConsumedResource('auth_api', 'GET', '/me', null, [new Response(200, new Body(null, $at))], $at),
            ],
            [
                new NamedSchema('PetList', new ArrayNode(new RefNode('Pet')), $at),
                new NamedSchema('Pet', new ObjectNode([
                    new Property('id', new PrimitiveNode('integer'), $at),
                    new Property('weight', new PrimitiveNode('float'), $at),
                    new Property('score', new PrimitiveNode('number'), $at),
                    new Property('vaccinated', new PrimitiveNode('boolean'), $at),
                    new Property('birth_date', self::flagged(new PrimitiveNode('string'), false, true), $at),
                    new Property('nickname', self::flagged(new PrimitiveNode('string'), true, false, 'Shown on the card'), $at),
                    new Property('status', new EnumNode(['sold', 'available']), $at),
                    new Property('tags', new ArrayNode(self::flagged(new PrimitiveNode('string'), false, true)), $at),
                    new Property('scores', new MapNode(new PrimitiveNode('number')), $at),
                    new Property(
                        'owner',
                        self::flagged(new ObjectNode([new Property('id', new PrimitiveNode('integer'), $at)]), true, true),
                        $at,
                    ),
                    new Property('payment', new UnionNode([
                        new UnionMember('pix', new RefNode('PixPayment')),
                        new UnionMember('card', new RefNode('CardPayment')),
                    ]), $at),
                    new Property('mother', self::flagged(new RefNode('Pet'), true, true, 'Known parent'), $at),
                ]), $at),
            ],
        );
    }

    private static function flagged(SchemaNode $node, bool $optional, bool $nullable, ?string $description = null): SchemaNode
    {
        $node->optional = $optional;
        $node->nullable = $nullable;
        $node->description = $description;

        return $node;
    }
